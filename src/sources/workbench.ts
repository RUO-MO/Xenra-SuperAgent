/**
 * Workbench: the entry where a person writes a request in the panel's console.
 *
 * This is a *channel*, not a work target. It owns no repository and no directory: what the request acts on is decided by
 * the deployment's `repository` (and, later, by an explicit workspace target). GitHub and Feishu are the same kind of thing
 * — they deliver a person's words; the repository is a deployment-wide fact that every worker inherits.
 *
 * Keeping workbench as a SourceKind means a console request takes the identical path as an Issue or a Feishu message:
 * Trigger -> Intake (dedupe, scope, thread correlation) -> Eval -> Ticket -> Executor -> reply. It never opens a ticket
 * directly, so authorization, assessment, audit trail and the reply channel stay intact.
 */
import type { Context } from '@deepseek-ai/cordis'
import { z } from 'zod'
import { key } from '../core/index.ts'
import type { OutboundMessage, Trigger } from '../core/index.ts'
import type { SourceKind } from './kind.ts'

export const SOURCE = 'workbench'

const WorkbenchConfigSchema = z.object({
  /** Who may originate work from the console, in the deployment's own vocabulary. Empty means nobody. */
  allowed: z.array(z.object({ id: z.string().trim().min(1).max(200), name: z.string().trim().max(100).optional() }).strict())
    .refine(users => new Set(users.map(user => user.id)).size === users.length, 'Duplicate user IDs').default([]),
}).strict()
export type WorkbenchConfig = z.infer<typeof WorkbenchConfigSchema>

/** A console request, before it becomes a Trigger. `id` is generated by the caller so a retry is a no-op. */
export interface WorkbenchRequest {
  id: string
  actor: string
  text: string
  at: string
  /** Optional human-declared limit on what may change; passed to the worker without interpretation. */
  scope?: string
}

/** Builds the Trigger for a console request. The thread is the target (`target`), not the entry channel. */
export function workbenchTrigger(request: WorkbenchRequest, target: string): Trigger {
  return {
    id: key('workbench-request', request.id),
    source: SOURCE,
    // One thread per target, so a console request and a GitHub/Feishu request about the same repository can meet on one
    // Ticket. `Intake`'s subscription fan-out already knows how to correlate them.
    threads: [{ source: SOURCE, id: target }],
    actor: { source: SOURCE, id: request.actor },
    human: true,
    // A request typed into the console is an explicit, direct request by construction.
    addressed: 'direct',
    at: request.at,
    text: request.text,
    meta: { target, ...(request.scope ? { scope: request.scope } : {}) },
  }
}

export const workbenchKind: SourceKind<WorkbenchConfig> = {
  kind: SOURCE,
  title: { zh: '工作台', en: 'Workbench' },
  description: { zh: '在面板里直接写下要求，作用于已配置的项目。', en: 'Write a request directly in the panel, acting on the configured project.' },
  schema: WorkbenchConfigSchema,
  fields: [
    { key: 'allowed', type: 'rows', label: { zh: '可以提要求的人', en: 'Who may make requests' },
      hint: { zh: '只有名单上的人从工作台提交的要求才会被接收；其余按评估设置处理。', en: 'Only requests from people on this list are admitted; the rest follow the evaluation settings.' },
      columns: [
        { key: 'id', type: 'text', label: { zh: '账号', en: 'Account' }, pattern: '[A-Za-z0-9._@-]+',
          placeholder: { zh: '例如：alice', en: 'For example alice' } },
        { key: 'name', type: 'text', label: { zh: '显示名', en: 'Display name' }, optional: true,
          placeholder: { zh: '例如：张三', en: 'For example Alice' } },
      ] },
  ],
  health: ['workbench'],
  scope({ meta }, config) {
    // The console is a private, first-party entry: every request it produces is listened to. Who may originate work is
    // decided by Policy's `allowed` list and `allowedSender`, not by hiding the request from the domain.
    if (typeof meta.target !== 'string' || !meta.target) return { listened: false, reason: 'workbench_no_target' }
    return { listened: true, observed: false, row: config.allowed.length ? 'listed' : 'default' }
  },
  channel: {
    // Replies are stored as part of the request's own record, so a workbench Thread never writes to an external service.
    send: async (_host, _message: OutboundMessage) => 'sent',
    link: (address) => ({ url: `#workbench/${address.target ?? ''}`, label: { zh: '工作台', en: 'Workbench' } }),
  },
  policy: {
    unnamed: { person: { zh: '工作台用户', en: 'Workbench user' }, bot: { zh: '工作台机器人', en: 'Workbench bot' } },
    schema: z.object({ allowed: WorkbenchConfigSchema.shape.allowed }).strict(),
    fields: [{ key: 'allowed', type: 'rows', label: { zh: '可以提要求的人', en: 'Who may make requests' }, columns: [
      { key: 'id', type: 'text', label: { zh: '账号', en: 'Account' }, pattern: '[A-Za-z0-9._@-]+',
        placeholder: { zh: '例如：alice', en: 'For example alice' } },
      { key: 'name', type: 'text', label: { zh: '显示名', en: 'Display name' }, optional: true },
    ] }],
    explicit: { zh: '在工作台里直接写下要求。', en: 'A request written directly in the workbench.' },
  },
  environment: {
    variables: [
      { key: 'XENRA_SUPERAGENT_WORKBENCH_TARGET', description: { zh: '这次要求作用的目标', en: 'The target this request acts on' } },
      { key: 'XENRA_SUPERAGENT_WORKBENCH_SCOPE', description: { zh: '提出要求的人声明的改动范围', en: 'The scope the requester declared' } },
    ],
    values: ({ trigger }) => ({
      XENRA_SUPERAGENT_WORKBENCH_TARGET: trigger?.source === SOURCE ? String(trigger.meta.target ?? '') : '',
      XENRA_SUPERAGENT_WORKBENCH_SCOPE: trigger?.source === SOURCE ? String(trigger.meta.scope ?? '') : '',
    }),
  },
}

export const name = 'xenra-superagent-workbench'
export const inject = ['orchestrator']
export function apply(ctx: Context): void {
  ctx.effect(() => {
    const unregister = ctx.orchestrator.sources.register(workbenchKind)
    // A console channel has no remote connection to establish: once registered it is ready, not perpetually `starting`.
    ctx.orchestrator.sources.healthEntries(workbenchKind.health).get(SOURCE)?.set({ state: 'ready',
      detail: 'Ready for requests', at: new Date().toISOString() })
    return unregister
  }, 'workbench: source kind')
}
